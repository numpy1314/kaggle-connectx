"""Build a self-contained submission.py from the search engine and opening book."""

import argparse
import base64
import json
import os
import platform
import shutil
import struct
import subprocess
import sys
import tempfile
import textwrap
import zlib
from pathlib import Path


ROOT = Path(__file__).resolve().parent
ENGINE = ROOT / "engine.c"
FLAGS = ["-std=gnu11", "-O3", "-Wall", "-Wextra", "-fvisibility=hidden"]
AMD64 = {"x86_64", "amd64"}


def build_host(path, extra=()):
    if sys.platform == "darwin":
        shared = ["-dynamiclib", "-Wl,-install_name,@rpath/engine.dylib"]
    else:
        shared = ["-shared", "-fPIC", "-s"]
    cpu_flags = ["-mpopcnt"] if platform.machine().lower() in AMD64 else []
    subprocess.run([
        os.environ.get("CC", "cc"), *FLAGS, *shared, *cpu_flags, *extra,
        "-o", str(path), str(ENGINE),
    ], check=True)


def build_linux(path):
    if sys.platform == "linux" and platform.machine().lower() in AMD64:
        compiler = [os.environ.get("CC", "cc")]
    else:
        clang = shutil.which("clang")
        linker = shutil.which("ld.lld")
        if clang is None or linker is None:
            raise SystemExit("A Linux x86-64 host or clang and ld.lld are needed to build the submission.")
        compiler = [clang, "--target=x86_64-linux-gnu", f"--ld-path={linker}"]
    subprocess.run([
        *compiler, *FLAGS,
        "-DCX_CROSS_LINUX", "-ffreestanding", "-fno-stack-protector", "-fPIC",
        "-mpopcnt", "-shared", "-nostdlib", "-Wl,-s", "-o", str(path), str(ENGINE),
    ], check=True)


def encoded_bytes(data, indent):
    encoded = base64.b64encode(zlib.compress(data, 9)).decode("ascii")
    return "\n".join(f"{indent}b'{line}'" for line in textwrap.wrap(encoded, width=96))


def pack_openings(book):
    if not book.exists():
        return b"", 0
    rows = json.loads(book.read_text(encoding="utf-8"))
    entries = {}
    for row in rows:
        key, column = row["key"], row["move"]
        if not 0 <= key < (1 << 49) or not 0 <= column < 7 or key in entries:
            raise ValueError(f"Invalid or duplicate opening entry: {row}")
        entries[key] = column
    return b"".join(struct.pack("<QB", key, column) for key, column in sorted(entries.items())), len(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--book", type=Path, default=ROOT / "openings.json")
    parser.add_argument("--output", type=Path, default=ROOT / "submission.py")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory(prefix="connectx-build-") as temp:
        directory = Path(temp)
        linux = directory / "engine.so"
        build_linux(linux)
        libraries = {("linux", "x86_64"): linux.read_bytes()}
        if sys.platform == "darwin":
            local = directory / "engine.dylib"
            build_host(local)
            libraries[(sys.platform, platform.machine().lower())] = local.read_bytes()

    native = ["_NATIVE_BLOBS = {"]
    for platform_key, data in libraries.items():
        native.extend((f"    {platform_key!r}: (", encoded_bytes(data, "        "), "    ),"))
    native.append("}")
    packed, count = pack_openings(args.book)
    opening = "_OPENING_BYTES = (\n" + encoded_bytes(packed, "    ") + "\n)"

    template = (ROOT / "agent.py").read_text(encoding="utf-8")
    source = template.replace(
        '"""Source template for the standalone Kaggle agent in submission.py."""',
        '"""Kaggle ConnectX agent. Generated by build_submission.py."""',
        1,
    ).replace(
        "_NATIVE_BLOBS = {}  # Filled by build_submission.py.", "\n".join(native), 1,
    ).replace(
        '_OPENING_BYTES = b""  # Filled by build_submission.py.', opening, 1,
    )
    compile(source, str(args.output), "exec")
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=args.output.parent, delete=False) as output:
        output.write(source)
    Path(output.name).replace(args.output)
    print(f"{args.output}: {args.output.stat().st_size:,} bytes, {count:,} opening positions")


if __name__ == "__main__":
    main()
